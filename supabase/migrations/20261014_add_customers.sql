create or replace function public.record_sale(p_customer_name text, p_payment_method text, p_product_id bigint, p_quantity integer, p_selling_price numeric, p_customer_id bigint default null) returns bigint language plpgsql security invoker as $$
declare v_stock integer; v_sale_id bigint; begin
  if p_quantity is null or p_quantity <= 0 then raise exception 'Sale quantity must be positive'; end if;
  select stock_qty into v_stock from public.products where product_id=p_product_id for update;
  if v_stock is null then raise exception 'Product not found'; end if;
  if v_stock < p_quantity then raise exception 'Insufficient stock: % available', v_stock; end if;
  insert into public.sales(customer_name,customer_id,payment_method) values(coalesce(nullif(p_customer_name,''),'Walk-in customer'),p_customer_id,p_payment_method) returning sale_id into v_sale_id;
  insert into public.sale_items(sale_id,product_id,quantity,selling_price) values(v_sale_id,p_product_id,p_quantity,p_selling_price);
  update public.products set stock_qty=stock_qty-p_quantity, updated_at=now() where product_id=p_product_id;
  insert into public.stock_movements(product_id,movement_type,quantity_change,reference_type,reference_id,remarks) values(p_product_id,'SALE',-p_quantity,'SALE',v_sale_id::text,'Sale recorded atomically');
  return v_sale_id;
end; $$;
